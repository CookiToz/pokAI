// Pixel-art contract. All art is authored as code (no binary assets) and
// rasterised to Phaser textures at boot by art/texture-factory.ts.
//
// Texture keys produced by the factory:
//   "tileset"                 spritesheet 16x16, frame i = TILE_NAMES[i]
//   "char:<id>"               spritesheet 16x16, 8 frames:
//                             0-1 down, 2-3 up, 4-5 left, 6-7 right (2-frame walk)
//   "portrait:<id>"           32x32 dialogue / battle-intro portrait (optional, falls back to none)
//   "pokai:<formId>"          32x32 front battle sprite
//   "pokai:<formId>:back"     32x32 back sprite (factory mirrors+darkens front if missing)
//   "pokai:<formId>:sealed"   generated by the factory: desaturated + red "CONFORME" ribbon
//   "pokai:unknown"           silhouette used for non-MVP forms
//   "ui:frame"                9-slice frame 24x24 (8px corners) for dialog boxes/menus
//   "ui:cursor", "ui:hp_bar", "ui:type:<typeId>" small UI pieces

export interface PixelSprite {
  w: number;
  h: number;
  // one char per pixel; '.' = transparent; other chars index `palette`
  rows: string[];
  palette: Record<string, string>; // char -> "#rrggbb"
}

export interface CharacterSheet {
  id: string; // e.g. "player", "lecube", "agent_conformite"
  frames: PixelSprite[]; // exactly 8, 16x16, layout above
  portrait?: PixelSprite; // 32x32
}

export interface PokaiSprite {
  formId: string;
  front: PixelSprite; // 32x32
  back?: PixelSprite;
}
